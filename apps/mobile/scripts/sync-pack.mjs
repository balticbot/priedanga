/**
 * Copy the canonical content pack (packs/dev) into the app as byte-exact
 * `.bin` assets. Metro would otherwise parse `.json` files into objects, and
 * the app must hash the exact bytes the manifest was signed over.
 */
import { copyFileSync, mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, '../../../packs/dev');
const dst = join(here, '../assets/pack');
const FILES = ['manifest.json', 'manifest.sig', 'trust.json', 'places.json', 'municipalities.json', 'guidance.json', 'checklists.json'];

rmSync(dst, { recursive: true, force: true });
mkdirSync(dst, { recursive: true });
const present = new Set(readdirSync(src));
for (const f of FILES) {
  if (!present.has(f)) throw new Error(`pack file missing: ${f} (run npm run pack)`);
  copyFileSync(join(src, f), join(dst, `${f}.bin`));
}
console.log(`synced ${FILES.length} pack files -> assets/pack/*.bin`);

// Region packs (map tiles + walking network) are large and git-ignored. Copy the
// ones that exist and generate the module that requires them, so the app builds
// with or without them.
const REGIONS = ['kaunas'];
const REGION_FILES = ['manifest.json', 'manifest.sig', 'tiles.pmtiles', 'walk.json'];
const regionDst = join(here, '../assets/region');
rmSync(regionDst, { recursive: true, force: true });
const available = [];
for (const id of REGIONS) {
  const srcDir = join(here, '../../../packs/regions', id);
  let files;
  try {
    files = new Set(readdirSync(srcDir));
  } catch {
    continue;
  }
  if (!REGION_FILES.every((f) => files.has(f))) continue;
  mkdirSync(join(regionDst, id), { recursive: true });
  for (const f of REGION_FILES) copyFileSync(join(srcDir, f), join(regionDst, id, `${f}.bin`));
  available.push(id);
}
const lines = [
  '// Generated by scripts/sync-pack.mjs. Do not edit.',
  "import type { RegionAssets } from './regionTypes';",
  '',
  'export const REGION_ASSETS: Record<string, RegionAssets> = {',
  ...available.map(
    (id) =>
      `  ${JSON.stringify(id)}: {\n` +
      REGION_FILES.map((f) => `    ${JSON.stringify(f)}: require('../../assets/region/${id}/${f}.bin'),`).join('\n') +
      '\n  },',
  ),
  '};',
  '',
];
mkdirSync(join(here, '../src/map'), { recursive: true });
writeFileSync(join(here, '../src/map/regionAssets.generated.ts'), lines.join('\n'));
console.log(`regions bundled: ${available.length ? available.join(', ') : 'none (run npm run region -- build kaunas)'}`);
